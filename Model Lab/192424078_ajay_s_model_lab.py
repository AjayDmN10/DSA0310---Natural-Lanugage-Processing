print("\nWord - POS Tag")
for word, tag in tags:
    print(word, "-", tag)
categories = {
 "Nouns": "NN",
 "Verbs": "VB",
 "Adjectives": "JJ",
 "Adverbs": "RB",
 "Pronouns": "PRP"
}
print("\nCategory Summary:")
for name, prefix in categories.items():
    count = sum(tag.startswith(prefix) for word, tag in tags)
    print(name, ":", count)

import nltk
print("INTELLIGENT GRAMMAR PARSING SYSTEM")
grammar = nltk.CFG.fromstring("""
S -> NP VP
NP -> Det N | Det Adj N | N
VP -> V NP | V
Det -> 'the' | 'a' | 'an'
Adj -> 'damaged' | 'new'
N -> 'customer' | 'product' | 'refund' | 'order'
V -> 'requested' | 'needs' | 'booked'
""")
parser = nltk.RecursiveDescentParser(grammar)
sentence = input("\nEnter a Sentence: ").lower()
words = sentence.replace(".", "").split()

try:
    trees = list(parser.parse(words))
    print("\nParsing Result:")
    if trees:
        print("Sentence is Grammatically Valid")
        for tree in trees:
            print(tree)
            tree.pretty_print()
    else:
        print("Sentence is Grammatically Invalid")
except ValueError as e:
    print("\nParsing Result:")
    print("Sentence is Grammatically Invalid (contains words not defined in the system grammar rules)")

import nltk
from nltk.corpus import wordnet as wn
nltk.download('wordnet')
nltk.download('omw-1.4')
print("SEMANTIC KNOWLEDGE EXPLORER")
word = input("\nEnter a Word: ").lower()
synsets = wn.synsets(word)
if not synsets:
    print("No WordNet Information Found")
else:
    for syn in synsets:
        print("\nSynset:", syn.name())
        print("Definition:", syn.definition())
        synonyms = set()
        for lemma in syn.lemmas():
            synonyms.add(lemma.name())
        print("Synonyms:", ", ".join(sorted(synonyms)))
        hyper = [h.name() for h in syn.hypernyms()]
        print("Hypernyms:", hyper if hyper else "None")
        hypo = [h.name() for h in syn.hyponyms()]
        print("Hyponyms:", hypo if hypo else "None")